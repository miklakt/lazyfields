# Dunders through which a trusted class's own code runs during loading, or hooks that intercept attribute
# access afterward. REDUCE can call a class directly instead of NEWOBJ, running __init__ for real, and
# BUILD restores slots with real setattr() calls - so both need the same scrutiny as __new__/__setstate__,
# not the free pass every other dunder gets.
_LOAD_TIME_HOOKS = {"__new__", "__init__", "__setattr__", "__setstate__", "__getstate__",
                    "__getattr__", "__getattribute__"}
# Exec'd from a generated source string into the class's own module - looks like the author's code by
# every measure except one: real code has a real source file.
_GENERATED_FROM_STRING = {"__init__", "__setattr__"}
# __post_init__ is never generated by dataclass() itself - only called, from __init__ - so its mere
# presence is always the class author's own code, reachable the same way __init__ is.
_ALWAYS_UNSAFE = {"__post_init__"}


def _generated_by_dataclass(name: str, value) -> bool:
    """Whether dataclass() produced this itself, not the class's own author.

    __setstate__/__getstate__ are literally dataclasses' own functions, reused as-is: their __module__
    says so. __init__ and frozen=True's __setattr__ are instead exec'd from a generated source string.
    """
    if name in _GENERATED_FROM_STRING:
        return getattr(getattr(value, "__code__", None), "co_filename", None) == "<string>"
    return getattr(value, "__module__", None) == "dataclasses"


def _unsafe_attribute(cls: type) -> str | None:
    """The name of the first attribute keeping cls from being data_only, or None if it is."""
    if type(cls) is not type:
        # Calling cls directly goes through type(cls).__call__ too - a custom metaclass's own code,
        # not cls's, so no per-attribute check here could catch it.
        return f"its metaclass {type(cls).__qualname__}"
    for base in cls.__bases__:
        if base is not object and _unsafe_attribute(base) is not None:
            return f"its base class {base.__qualname__}"
    for name, value in vars(cls).items():
        if name in _ALWAYS_UNSAFE:
            return name
        if name in _LOAD_TIME_HOOKS:
            if not _generated_by_dataclass(name, value):
                return name
        elif not (name.startswith("__") and name.endswith("__")):
            if isinstance(value, types.MemberDescriptorType):
                continue  # A slots= field: reads and writes storage, nothing more.
            if callable(value) or hasattr(type(value), "__get__"):
                return name
    return None


def data_only(cls: type) -> bool:
    """Whether cls is safe to pass as trust=: nothing on it a crafted pickle could run or call.

    Building and restoring state never runs a class's own code unless it defines __new__ or
    __setstate__ - those are checked for here. Everything else data-only needs is already covered by
    the getattr() gadget staying blocked: no method, property, or other descriptor for it to resolve.
    Requires a plain base (object, or nothing but another data_only class) so nothing is inherited in.
    """
    return _unsafe_attribute(cls) is None


def _trust(trust):
    """Normalize one reader's trust: None is the safe allowlist and True is unrestricted."""
    if trust is True:
        return None
    if trust is None:
        return frozenset()
    targets = (trust,) if isinstance(trust, (str, type)) or (
        isinstance(trust, tuple) and len(trust) == 2 and all(isinstance(item, str) for item in trust)) else trust
    trusted = set()
    for target in targets:
        if isinstance(target, str): trusted.add(target)
        elif isinstance(target, type):
            if (unsafe := _unsafe_attribute(target)) is not None:
                raise ValueError(f"{target.__qualname__} is not safe to trust: {unsafe} could run during loading.")
            trusted.add((target.__module__, target.__qualname__))
        elif isinstance(target, tuple) and len(target) == 2 and all(isinstance(item, str) for item in target):
            trusted.add(target)
        else: raise TypeError("trust needs classes, module prefixes, or (module, name) pairs.")
    return frozenset(trusted)


def _trusted(module, name, trust):
    return (trust is None or (module, name) in _ALLOWED or (module, name) in trust or
            _prefix(module, trust) is not None)


def _prefix(module, trust):
    return next((prefix for prefix in trust if isinstance(prefix, str) and
                 (module == prefix or module.startswith(prefix + "."))), None)


def _positional(items) -> dict[str, Any]:
    return {str(index): item for index, item in enumerate(items)}


def _plain_fields(parts):
    """parts's state, if the proxy it belongs to is shaped like an ordinary object's default pickle:
    no constructor args or kwargs, no sequence/mapping items of its own, just its real attributes as
    state (a __slots__ class's (dict, slots_dict) pair is already merged into one by __setstate__, so
    it qualifies too). None otherwise - a namedtuple-style REDUCE call keeps its envelope instead,
    since there is no single flat set of real attribute names to show.
    """
    state = parts.get("state")
    if not parts.get("args") and "kwargs" not in parts and "items" not in parts and isinstance(state, dict):
        return state
    return None


class _Proxy(Mapping):
    """An object of a type that is not data, as its parts instead of the object: browsable, never run.

    Pickling calls the type, or its constructor function, with args, then gives the object its state and items.
    The proxy keeps each of those as given; args, and a state tuple with no special meaning of its own,
    become positional mappings, so their contents stay reachable.

    An ordinary object's state is already its __dict__, real attribute names included - so browsing
    shows that dict's own keys directly as the proxy's children, in place of the type/args/state
    envelope, the same layout a trusted, Mapping-shaped version of the class would have. Code in this
    module that needs the envelope itself (_get and friends) reads proxy._parts directly instead of
    going through this Mapping view, so that reconstructors are unaffected by what browsing shows.
    """

    type: str
    __eq__ = object.__eq__
    __hash__ = object.__hash__

    def __new__(cls, *args, **kwargs):
        proxy = super().__new__(cls)
        proxy._parts = {"type": cls.type, "args": _positional(args)} | ({"kwargs": kwargs} if kwargs else {})
        return proxy

    def __init__(self, *args, **kwargs):
        pass

    def __getitem__(self, key):
        try:
            return self._parts[key]
        except KeyError:
            fields = _plain_fields(self._parts)
            if fields is not None and key in fields:
                return fields[key]
            raise

    def __iter__(self):
        return iter(_plain_fields(self._parts) or self._parts)

    def __len__(self):
        return len(_plain_fields(self._parts) or self._parts)

    def __setstate__(self, state):
        dict_pair = (isinstance(state, tuple) and len(state) == 2
                     and all(part is None or isinstance(part, dict) for part in state))
        if dict_pair:
            # Pickle's own BUILD convention for a 2-tuple state - a __slots__ class, typically: dict
            # state and slot state, both merged into the instance's real attributes either way, not a
            # positional pair. Without this, "0"/"1" would masquerade as the object's own field names.
            dict_state, slot_state = state
            self._parts["state"] = {**(dict_state or {}), **(slot_state or {})}
        elif isinstance(state, tuple):
            self._parts["state"] = _positional(state)
        else:
            self._parts["state"] = state

    def __setitem__(self, key, value):
        self._parts.setdefault("items", {})[key] = value

    def extend(self, values):
        items = self._parts.setdefault("items", {})
        items.update(_positional([*items.values(), *values]))

    def append(self, value):
        self.extend([value])

    def __call__(self, *args, **kwargs):  # Calling a proxied object is proxied too.
        return _proxy_type(f"{self.type}()")(*args, **kwargs)


@lru_cache(maxsize=None)
def _proxy_type(name: str) -> type[_Proxy]:
    """A stand-in for the global name: calling it proxies the call, and nothing named is imported."""
    return type(name.rpartition(".")[2], (_Proxy,), {"type": name})


def _resolved(module: str, name: str, trust=frozenset()):
    """A data type's global as a reference for the scan, or the proxy type standing in for any other."""
    name = module, name
    return _Ref(name) if _trusted(*name, trust) else _proxy_type(".".join(name))


def _safe_getattr(value, name, trust):
    """Restore bound methods only for objects covered by this reader's trust."""
    cls = value if isinstance(value, type) else type(value)
    if (not isinstance(name, str) or name.startswith("__") or
            not ((cls.__module__, cls.__qualname__) in trust or _prefix(cls.__module__, trust))):
        return _proxy_type("builtins.getattr")(value, name)
    return getattr(value, name)


class _DataUnpickler(pickle.Unpickler):
    """Builds data types; other globals become proxy types. Persistent IDs and out-of-band buffers stay refused."""

    def __init__(self, file, trust):
        super().__init__(file, fix_imports=False)
        self.trust = trust
        self.refused = []  # Globals turned into proxies instead of built for real, in encounter order.

    def find_class(self, module, name):
        qualified = module, name
        if self.trust is None:
            return super().find_class(*qualified)
        if qualified == ("builtins", "getattr"):
            return partial(_safe_getattr, trust=self.trust)
        if qualified in _ALLOWED or qualified in self.trust:
            return super().find_class(*qualified)
        if prefix := _prefix(qualified[0], self.trust):
            value = super().find_class(*qualified)
            origin = getattr(value, "__module__", None)
            if origin == prefix or isinstance(origin, str) and origin.startswith(prefix + "."):
                return value
        self.refused.append(".".join(qualified))
        return _proxy_type(".".join(qualified))


def _get(value, key):
    """value's raw part named key - a proxy's own type/args/kwargs/state/items, never its flattened
    browsing view - or value[key] for a plain dict; None if value supports neither.
    """
    if isinstance(value, _Proxy):
        return value._parts.get(key)
    return value.get(key) if isinstance(value, Mapping) else None


def _path(value, *keys):
    """value's nested raw part at each key in turn, via _get; None as soon as one is missing."""
    for key in keys:
        value = _get(value, key)
    return value


def _proxy_of(value, type_name):
    """Whether value is a proxy of exactly type_name."""
    return isinstance(value, _Proxy) and value.type == type_name


def _manager(proxy, manager_type):
    """proxy's _mgr, if it's a Proxy of exactly manager_type."""
    manager = _path(proxy, "state", "_mgr")
    return manager if _proxy_of(manager, manager_type) else None


def _index_values(index_proxy):
    """The real plain values behind one axis's Index, or None if its shape isn't recognized."""
    if not _proxy_of(index_proxy, "pandas.core.indexes.base._new_Index"):
        return None
    import numpy as np

    kwargs = _path(index_proxy, "args", "1")
    if not isinstance(kwargs, dict):
        return None
    data = kwargs.get("data")
    if isinstance(data, np.ndarray):
        return data
    if _proxy_of(data, "pandas._libs.arrays.__pyx_unpickle_NDArrayBacked"):
        # A pandas string (or other NDArrayBacked) extension array: its raw values, dtype ignored.
        values = _path(data, "state", "1")
        return values if isinstance(values, np.ndarray) else None
    # A RangeIndex has no "data" at all, just its own bounds - the common case for any DataFrame or
    # Series built without an explicit index.
    bounds = (kwargs.get("start"), kwargs.get("stop"), kwargs.get("step"))
    if data is None and all(isinstance(bound, int) for bound in bounds):
        return np.arange(*bounds)
    return None


def _dataframe(proxy):
    """A real DataFrame, rebuilt by pandas' own public constructor from already-real column arrays
    and index values - or None if this proxy's shape isn't the one recognized here.

    Only ever reads a proxy's parts; nothing from the pickle is imported or called to get here, and
    the one piece of pandas code that runs is the ordinary, public DataFrame(...) constructor.
    """
    import numpy as np

    manager = _manager(proxy, "pandas.core.internals.managers.BlockManager")
    if manager is None:
        return None
    blocks, axes = _path(manager, "args", "0"), _path(manager, "args", "1")
    if not (isinstance(blocks, tuple) and isinstance(axes, list) and len(axes) == 2):
        return None
    columns, index = _index_values(axes[0]), _index_values(axes[1])
    if columns is None or index is None:
        return None
    series = [None] * len(columns)
    for block in blocks:
        if not _proxy_of(block, "pandas._libs.internals._unpickle_block"):
            return None
        array, placement = _path(block, "args", "0"), _path(block, "args", "1")
        if not (isinstance(array, np.ndarray) and array.ndim == 2 and isinstance(placement, slice)):
            return None
        for row, position in enumerate(range(*placement.indices(len(columns)))):
            series[position] = array[row]
    if any(column is None for column in series):
        return None
    # Depth to the caller of _load() varies with how deeply this proxy is nested, so stacklevel can't
    # reliably point past this module; the message names what matters instead of where it's raised from.
    warnings.warn(
        "Rebuilding a DataFrame from an untrusted pickle using only its raw column and index arrays, "
        "through pandas' public constructor - not the pickle's own pandas-specific reconstruction. "
        "Extension dtypes, categoricals, MultiIndex, attrs and flags are not preserved this way; pass "
        "trust=[\"pandas\"] for an exact reconstruction.")
    import pandas as pd
    return pd.DataFrame(dict(zip(columns, series)), index=index)


def _series(proxy):
    """A real Series, rebuilt the same way as _dataframe: from its own SingleBlockManager, which
    holds the axis Index and the data array directly, not grouped into column blocks.
    """
    import numpy as np

    manager = _manager(proxy, "pandas.core.internals.managers.SingleBlockManager")
    if manager is None:
        return None
    state = _get(manager, "state")
    if not isinstance(state, dict):
        return None
    axes, values = state.get("0"), state.get("1")
    if not (isinstance(axes, list) and len(axes) == 1 and isinstance(values, list) and len(values) == 1):
        return None
    index, array = _index_values(axes[0]), values[0]
    if index is None or not isinstance(array, np.ndarray):
        return None
    warnings.warn(
        "Rebuilding a Series from an untrusted pickle using only its raw data and index arrays, "
        "through pandas' public constructor - not the pickle's own pandas-specific reconstruction. "
        "Extension dtypes, attrs and flags are not preserved this way; pass trust=[\"pandas\"] for "
        "an exact reconstruction.")
    import pandas as pd
    return pd.Series(array, index=index, name=_path(proxy, "state", "_name"))


def _index(proxy):
    """A real Index or RangeIndex, rebuilt from its own already-real values or bounds."""
    values = _index_values(proxy)
    if values is None:
        return None
    warnings.warn(
        "Rebuilding an Index from an untrusted pickle using only its raw values, through pandas' "
        "public constructor - not the pickle's own pandas-specific reconstruction. A named or typed "
        "Index subclass is not preserved this way; pass trust=[\"pandas\"] for an exact reconstruction.")
    import pandas as pd
    return pd.Index(values)


# Each entry rebuilds one proxy type as a real object from already-safe data, through that type's
# own public constructor - or declines (None), left an inert proxy, if its shape isn't recognized.
# A proxy's type being listed here is what _kind() uses to call it a dataset ahead of loading, and
# what lets the browser still offer to Browse its pickle internals once loaded, side by side with that.
_RECONSTRUCTORS: dict[str, Callable[[Any], Any]] = {
    "pandas.DataFrame": _dataframe,
    "pandas.Series": _series,
    "pandas.core.indexes.base._new_Index": _index,
}


def _reconstructed(value, seen=None):
    """value with any proxy whose type has a registered reconstructor rebuilt as a real object;
    everything else is only walked for proxies to recognize deeper in, never altered itself.

    seen tracks every container already visited, by id(): pickled data routinely shares or even
    cycles back on itself, so walking naively would recurse forever on perfectly ordinary data,
    not just adversarial input.
    """
    seen = {} if seen is None else seen
    if id(value) in seen:
        return seen[id(value)]
    if isinstance(value, _Proxy):
        reconstruct = _RECONSTRUCTORS.get(value.type)
        reconstructed = reconstruct(value) if reconstruct else None
        if reconstructed is not None:
            seen[id(value)] = reconstructed
            return reconstructed
        seen[id(value)] = value
        parts = value._parts
        for part in ("args", "items"):
            for key, nested in parts.get(part, {}).items():
                parts[part][key] = _reconstructed(nested, seen)
        if "state" in parts:
            parts["state"] = _reconstructed(parts["state"], seen)
        return value
    if isinstance(value, dict):
        seen[id(value)] = value
        for key, nested in value.items():
            value[key] = _reconstructed(nested, seen)
        return value
    if isinstance(value, list):
        seen[id(value)] = value
        for index, nested in enumerate(value):
            value[index] = _reconstructed(nested, seen)
        return value
    if isinstance(value, tuple):
        result = tuple(_reconstructed(item, seen) for item in value)
        seen[id(value)] = result
        return result
    return value


def _load(path: str | Path, trust=frozenset()) -> Any:
    with open(path, "rb") as file:
        for name, _ in _operations(file):
            if name.startswith("EXT") and trust is not None:
                raise pickle.UnpicklingError(f"Pickle opcode {name} is not supported.")
            if not name.startswith("EXT") and name not in _OPCODES:
                raise pickle.UnpicklingError(f"Pickle opcode {name} is not supported.")
            if name == "STOP": break
        file.seek(0)
        unpickler = _DataUnpickler(file, trust)
        try:
            return _reconstructed(unpickler.load())
        except Exception as error:
            # A trusted class can itself depend on a global this trust didn't cover: that global
            # becomes an inert proxy, the trusted class gets handed the proxy instead of what it
            # expected, and fails confusingly deep inside its own code. The failure itself names
            # none of this, so it's worth surfacing here.
            if trust is not None and unpickler.refused:
                refused = ", ".join(dict.fromkeys(unpickler.refused))
                raise pickle.UnpicklingError(
                    f"{error} (this trust did not cover: {refused} - if what failed needed any of "
                    "these, add them to trust)") from error
            raise


def pickle_load(path: str | Path) -> Any:
    """Load modern pickle data using the safe built-in allowlist."""
    return _load(path)


@dataclass(eq=False)
class _Ref:
    """A global, or what calling it builds, as the scan records it without building; args is None until called."""

    name: tuple[str, str] | None
    args: Any = None
    state: Any = None


def _operations(file) -> Iterable[tuple[str, Any]]:
    """Opcode names and arguments; large byte payloads are skipped, their contents never read."""
    first = True
    while code := file.read(1):
        operation = pickletools.code2op[code.decode("latin-1")]
        descriptor = operation.arg
        if descriptor is not None and descriptor.name in _PAYLOADS:
            size = int.from_bytes(file.read(_PAYLOADS[descriptor.name]), "little")
            if size <= _INLINE:
                argument = file.read(size)
            else:
                file.seek(size, 1)
                argument = _Ref(("builtins", "bytes"), ())
        else:
            argument = descriptor and descriptor.reader(file)
        if first:
            if operation.name != "PROTO" or argument not in (4, 5):
                raise pickle.UnpicklingError("Only pickle protocols 4 and 5 are supported.")
            first = False
        yield operation.name, argument
    raise ValueError("Pickle ends without STOP.")


def _call(function, args, kwargs=None):
    """What calling function with args builds, so far as scanning can know without running it."""
    if isinstance(function, (type, _Proxy)):  # Proxy types, and proxies, track the call the same way loading does.
        return function(*args, **(kwargs or {}))
    name = function.name if isinstance(function, _Ref) and function.args is None else None
    if name in _MAPPINGS:  # Rebuilt as dicts, so their items fill in and paths reach them.
        return {}
    return b"" if name == ("builtins", "bytes") and not args else _Ref(name, args)


_CONSTANTS = {"NONE": lambda: None, "NEWTRUE": lambda: True, "NEWFALSE": lambda: False, "EMPTY_DICT": dict,
              "EMPTY_LIST": list, "EMPTY_TUPLE": tuple, "EMPTY_SET": lambda: _Ref(("builtins", "set"), ())}


def _scan(file, trust=frozenset()):
    """The pickled structure: containers and plain values, with references for anything to build."""
    stack, memo, marks = [], {}, []

    def take(count=None):
        """The top count items, or those above the last mark, removed from the stack."""
        start = marks.pop() if count is None else len(stack) - count
        items = stack[start:]
        del stack[start:]
        return items

    for name, argument in _operations(file):
        if name == "STOP":
            return stack.pop()
        if name in _VALUES:
            stack.append(argument)
        elif name in _CONSTANTS:
            stack.append(_CONSTANTS[name]())
        elif name == "MARK":
            marks.append(len(stack))
        elif name == "MEMOIZE":
            memo[len(memo)] = stack[-1]
        elif name in ("BINGET", "LONG_BINGET"):
            stack.append(memo[argument])
        elif name in ("TUPLE1", "TUPLE2", "TUPLE3", "TUPLE"):
            stack.append(tuple(take(int(name[-1]) if name[-1].isdigit() else None)))
        elif name in ("APPEND", "APPENDS"):
            items = take(1 if name == "APPEND" else None)
            if isinstance(stack[-1], (list, _Proxy)):
                stack[-1].extend(items)
        elif name in ("SETITEM", "SETITEMS"):
            items = take(2 if name == "SETITEM" else None)
            if isinstance(stack[-1], (dict, _Proxy)):
                for key, value in zip(items[::2], items[1::2]):
                    stack[-1][key] = value
        elif name in ("FROZENSET", "ADDITEMS"):
            take()
            if name == "FROZENSET":
                stack.append(_Ref(("builtins", "frozenset"), ()))
        elif name == "STACK_GLOBAL":
            stack.append(_resolved(*take(2), trust))
        elif name in ("REDUCE", "NEWOBJ", "NEWOBJ_EX"):
            stack.append(_call(*take(3 if name == "NEWOBJ_EX" else 2)))
        elif name == "BUILD":
            state, = take(1)
            if isinstance(stack[-1], _Proxy):
                stack[-1].__setstate__(state)
            elif isinstance(stack[-1], _Ref):
                stack[-1].state = state
        elif name == "NEXT_BUFFER":
            stack.append(_Ref(("builtins", "bytes"), ()))
        elif name not in ("PROTO", "FRAME", "READONLY_BUFFER"):
            raise ValueError(f"Pickle opcode {name} is not supported; it may need objects outside the file.")
    raise ValueError("Pickle ends without STOP.")


@lru_cache(maxsize=16)
def _scanned(path: str, size: int, modified: int, trust):
    with open(path, "rb") as file:
        return _scan(file, trust)


def _structure(path, key, trust=frozenset()):
    """The structure at key, scanned once per file version."""
    stat = Path(path).stat()
    return _path_get(_scanned(str(path), stat.st_size, stat.st_mtime_ns, trust), key or "")


def _parts(node) -> Iterable:
    if isinstance(node, _Ref):
        return node.args, node.state
    if isinstance(node, Mapping):
        return node.values()
    return node if isinstance(node, (list, tuple)) else ()


def _plain(node) -> bool:
    """Whether node holds only values the scan read, with nothing left to build."""
    return not isinstance(node, _Ref) and all(map(_plain, _parts(node)))


def _kind(node) -> NodeKind:
    if isinstance(node, _Ref):
        return "scalar" if node.name in _SCALARS else "dataset"
    # Loading may still turn this into a real dataset value, even though scanning alone - never
    # building anything - can't yet tell whether this particular one has the exact shape that needs.
    if isinstance(node, _Proxy) and node.type in _RECONSTRUCTORS:
        return "dataset"
    return value_kind(node)


def _dtype(node) -> str | None:
    if not isinstance(node, _Ref) or node.name != ("numpy", "dtype") or not isinstance(node.state, tuple):
        return None
    code, order, fields = node.args[0], node.state[1], node.state[3]
    if fields is not None:  # Structured dtypes need their fields built.
        return None
    import numpy as np
    return str(np.dtype(order + code if order in "<>" else code))


def _array(node) -> NodeInfo | None:
    """The dtype and shape of a NumPy array the pickle would build."""
    if not isinstance(node, _Ref):
        return None
    if node.name == ("numpy._core.multiarray", "_reconstruct") and isinstance(node.state, tuple):
        shape, dtype = node.state[1], _dtype(node.state[2])
    elif node.name == ("numpy._core.numeric", "_frombuffer"):
        shape, dtype = node.args[2], _dtype(node.args[1])
    else:
        return None
    # Object arrays are described by the dtype their loaded items share, as in-memory values are.
    return None if dtype in (None, "object") else NodeInfo("dataset", dtype=dtype, shape=tuple(shape),
                                                          type="numpy.ndarray")


def _inspect_node(path, key=None, *, trust=frozenset()) -> NodeInfo:
    node = _structure(path, key, trust)
    kind = _kind(node)
    if kind == "group":
        return NodeInfo(kind, tuple(str(name) for name, _ in _group_entries(node)),
                        type=node.type if isinstance(node, _Proxy) else None)
    if kind == "scalar":
        return NodeInfo(kind)
    if isinstance(node, _Proxy):
        # A registered reconstructor recognized this as a dataset - independent of _plain()/_array(),
        # which only make sense for a _Ref's own already-scanned content, not a proxy's parts. Its
        # children are listed anyway, so Browse still reaches the pickle internals underneath.
        return NodeInfo(kind, tuple(str(name) for name, _ in _group_entries(node)), type=node.type)
    if (array := _array(node)) is not None:
        return array
    if _plain(node):
        return value_info(node)
    return NodeInfo(kind, type=".".join(node.name) if isinstance(node, _Ref) else None)


def _inspect(path, key=None, *, trust=frozenset()) -> Iterable[tuple[str, NodeKind, Any]]:
    node = _structure(path, key, trust)
    if _kind(node) != "group":
        raise NotADirectoryError(key)
    loaded = None
    for name, child in _group_entries(node):
        kind = _kind(child)
        if kind == "scalar" and not _plain(child):  # Dates, decimals and skipped bytes show their loaded value.
            loaded = _path_get(_load(path, trust), key or "") if loaded is None else loaded
            child = _path_get(loaded, str(name))
        yield str(name), kind, child if kind == "scalar" else None


def pickle_reader(*, trust=None) -> Reader:
    """A protocol 4/5 reader whose trusted classes and module prefixes are local to the reader."""
    trust = _trust(trust)
    return Reader(partial(_load, trust=trust), inspect=partial(_inspect, trust=trust),
                  inspect_node=partial(_inspect_node, trust=trust), suffixes=(".pkl", ".pickle"), format="pickle")


PICKLE = pickle_reader()
